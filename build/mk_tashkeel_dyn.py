def check(slug):
    sp = os.path.join(ROOT, "audio", "scripts", "dynasties-%s.json" % slug)
    d = json.load(open(sp, encoding="utf-8"))
    want = [(s["id"], [p["say"] for p in s["parts"]]) for s in d["sections"]]
    got = [(i, ps) for i, _t, ps in T[slug]]
    if [w[0] for w in want] != [g[0] for g in got]:
        return ["أقسام مختلفة: %s" % [w[0] for w in want]]
    errs = []
    for (sid, wp), (_, gp) in zip(want, got):
        if len(wp) != len(gp):
            errs.append("%s: عدد المقاطع %d ≠ %d" % (sid, len(wp), len(gp)))
            continue
        for n, (a, b) in enumerate(zip(wp, gp), 1):
            if bare(a) != bare(b):
                A, B = bare(a), bare(b)
                k = next((j for j in range(min(len(A), len(B))) if A[j] != B[j]), min(len(A), len(B)))
                errs.append("%s-%d: اختلاف عند %d (طول %d/%d)\n  الأصل: %s\n  المشكول: %s" % (sid, n, k, len(A), len(B), A[max(0, k - 45):k + 45], B[max(0, k - 45):k + 45]))
    return errs


def main():
    bad = 0
    for slug in T:
        e = check(slug)
        if e:
            bad += 1
            print("×", slug)
            for x in e:
                print("  ", x)
            continue
        data = dict(slug=slug, kind="dynasties", narrated_only=True,
                    sections=[dict(id=i, title=t, parts=p) for i, t, p in T[slug]])
        open(os.path.join(ROOT, "audio", "scripts", "dynasties-%s.tashkeel.json" % slug), "w",
             encoding="utf-8").write(json.dumps(data, ensure_ascii=False, indent=1))
        print("✓", slug, sum(len(x) for _, _, ps in T[slug] for x in ps), "حرفًا")
    print("pages:", len(T), "errors:", bad)


if __name__ == "__main__":
    main()
